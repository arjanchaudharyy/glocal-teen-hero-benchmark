"""
Corpus loader for the Glocal Teen Hero dataset.

The corpus is 192 Nepal honorees (2015-2025), each scored on the record they held
AT SELECTION (the teen record the jury saw), with a separate `now` trajectory note
and source links. Data lives in data/heroes.json, generated by build.py.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from functools import lru_cache
from typing import Dict, List, Optional

_HERE = os.path.dirname(os.path.abspath(__file__))
_DATA = os.path.join(os.path.dirname(_HERE), "data", "heroes.json")


@dataclass(frozen=True)
class Hero:
    name: str
    year: int
    award: str                      # Winner | Finalist | 20under20 | Applicant
    scores: Dict[str, float]
    conf: str                       # high | med | low
    then: str                       # at-selection record
    now: str                        # later trajectory
    links: Dict[str, str] = field(default_factory=dict)
    est: bool = False               # heuristic estimate (low footprint)
    me: bool = False                # the applicant

    @property
    def doc(self) -> str:
        """Retrieval document: name + at-selection record + fields."""
        return f"{self.name} ({self.year}, {self.award}). {self.then}"

    @property
    def key(self) -> str:
        return f"{self.name}|{self.year}"


@dataclass(frozen=True)
class Corpus:
    heroes: List[Hero]
    rubric: dict

    def __iter__(self):
        return iter(self.heroes)

    def __len__(self):
        return len(self.heroes)

    def by_tier(self, tier: str) -> List[Hero]:
        return [h for h in self.heroes if h.award == tier]

    @property
    def winners(self) -> List[Hero]:
        return self.by_tier("Winner")

    @property
    def applicant(self) -> Optional[Hero]:
        return next((h for h in self.heroes if h.me), None)

    def get(self, name: str, year: Optional[int] = None) -> Optional[Hero]:
        for h in self.heroes:
            if h.name.lower() == name.lower() and (year is None or h.year == year):
                return h
        return None


@lru_cache(maxsize=1)
def load(path: str = _DATA) -> Corpus:
    with open(path, encoding="utf-8") as f:
        raw = json.load(f)
    heroes = [
        Hero(
            name=h["name"], year=h["year"], award=h["award"], scores=h["s"],
            conf=h.get("conf", "med"), then=h.get("then", ""), now=h.get("now", ""),
            links=h.get("links", {}) or {}, est=h.get("est", False), me=h.get("me", False),
        )
        for h in raw["heroes"]
    ]
    return Corpus(heroes=heroes, rubric=raw.get("rubric", {}))
